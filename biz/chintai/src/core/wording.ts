// 言ってはいけない言い方の一覧。
// この道具は、断定（払わなくてよい、外せます）、あおり（ぼったくり）、相場での判定、
// 必ず下がるという期待を、言わないと決めている。テストが、項目のデータと点検の結果の文を、これで確かめる。
// 画面や LP の文を書く人も、findBannedPhrase で自分の文を確かめられる。

export const BANNED_PHRASES: RegExp[] = [
  /ぼったくり/,
  /払わなくて(よい|いい|大丈夫)/,
  /払う必要は(ない|ありません)/,
  /支払う必要は(ない|ありません)/,
  /外せます(?!か)/, // 「外せますか」という質問はよい
  /断れます(?!か)/,
  /必ず(下が|安く|外せ|返って)/,
  /違法/,
  /不当な(請求|費用)/,
  /相場より/,
  /割高/,
  /高すぎ/,
  /安すぎ/,
  /損をしています/,
  /交渉すれば/,
  /値下げ(でき|して)/,
]

/** 確認の文面に、出してはいけない言葉（法律を振りかざさない）。 */
export const LEGAL_WORDS = /法律|法令|民法|告示|ガイドライン|違反|国土交通省|消費者|判決|第\d+条|条文/

/** 文の中に、言ってはいけない言い方があれば、最初に見つかったものを返す。なければ null。 */
export function findBannedPhrase(text: string): string | null {
  for (const re of BANNED_PHRASES) {
    const m = re.exec(text)
    if (m) return m[0]
  }
  return null
}
