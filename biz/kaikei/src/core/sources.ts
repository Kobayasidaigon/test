// 法令や通達は改正されるので、ときどき開き直して確かめ、そのたびに checkedOn を書きかえること（紹介のページの「◯年◯月◯日に確かめました」は、ここから出る）。
// 確かめられなかったことは、ここに入れていない（src/core/README.md の「できていないこと・あやしいところ」を見る）。

export type Fact = {
  id: string
  /** 事実を、ふつうの言葉で短く書いたもの。画面に出すときは、この範囲をこえて言い切らない */
  claim: string
  /** 出典 */
  source: {
    /** 文書の名前 */
    title: string
    /** 出している役所 */
    publisher: string
    url: string
  }
  /** 根拠になる条文や通達の番号（あれば） */
  basis?: string
  /** 確かめた日 */
  checkedOn: string
  /**
   * 確かめ方。
   *   'page' … ページを開いて、本文で確かめた
   *   'search-excerpt' … 検索結果に出た、公式サイトのページの抜粋で確かめた（本文は開けていない）
   */
  how: 'page' | 'search-excerpt'
}

