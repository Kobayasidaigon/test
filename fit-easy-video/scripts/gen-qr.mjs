// QRコード（法人契約のご案内ページ）をベクターSVGとして生成し src/qr.js に書き出す
import QRCode from 'qrcode';
import fs from 'node:fs';

const URL = 'https://shops.fiteasy.jp/corporate-membership';
const qr = QRCode.create(URL, { errorCorrectionLevel: 'Q' });
const n = qr.modules.size;
const margin = 2; // カード自体の白い余白と合わせて十分なクワイエットゾーンになる
const size = n + margin * 2;
let d = '';
for (let r = 0; r < n; r++) {
  let c = 0;
  while (c < n) {
    if (qr.modules.get(r, c)) {
      let run = 1;
      while (c + run < n && qr.modules.get(r, c + run)) run++;
      d += `M${c + margin} ${r + margin}h${run}v1h-${run}z`;
      c += run;
    } else c++;
  }
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges"><rect width="${size}" height="${size}" fill="#fff"/><path d="${d}" fill="#14171e"/></svg>`;
fs.writeFileSync(new URL_('../src/qr.js'), `// generated by scripts/gen-qr.mjs — ${URL}\nwindow.QR_SVG = ${JSON.stringify(svg)};\nwindow.QR_URL = ${JSON.stringify(URL)};\n`);
fs.writeFileSync(new URL_('../out/qr.svg'), svg);
console.log(`QR version ${qr.version}, ${n}x${n} modules, EC=Q`);
function URL_(p) { return new globalThis.URL(p, import.meta.url); }
